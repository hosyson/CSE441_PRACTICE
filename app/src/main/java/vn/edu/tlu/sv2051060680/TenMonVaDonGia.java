package vn.edu.tlu.sv2051060680;

public class TenMonVaDonGia {
    private String tenMon;
    private float donGia;

    public TenMonVaDonGia(String tenMon, float donGia) {
        this.tenMon = tenMon;
        this.donGia = donGia;
    }

    public String getTenMon() {
        return tenMon;
    }

    public float getDonGia() {
        return donGia;
    }
}
